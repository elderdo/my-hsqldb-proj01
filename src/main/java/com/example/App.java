package com.example;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.Statement;

public class App {
    public static void main(String[] args) {
        // "file:db/testdb" creates a local, file-based database in a folder named 'db'
          try {
            // Force load the driver into memory
            Class.forName("org.hsqldb.jdbc.JDBCDriver");
        } catch (ClassNotFoundException e) {
            System.err.println("HSQLDB Driver not found on classpath!");
            e.printStackTrace();
            return;
        }

        String url = "jdbc:hsqldb:file:db/testdb;shutdown=true";
        String user = "SA";
        String password = "";

        try (Connection conn = DriverManager.getConnection(url, user, password);
             Statement stmt = conn.createStatement()) {

            System.out.println("Creating sample table...");
            stmt.executeUpdate("CREATE TABLE IF NOT EXISTS users (" +
                               "id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                               "name VARCHAR(50))");

            stmt.executeUpdate("INSERT INTO users (name) VALUES ('Douglas')");
            System.out.println("Database successfully created and populated!");

        } catch (Exception e) {
            e.printStackTrace();
        }
    }
}

